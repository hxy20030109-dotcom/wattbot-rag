"""Build an honest report from completed, officially scored baseline artifacts."""

import argparse
import json
from collections import Counter
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--output-dir", type=Path, default=root / "outputs/holdout_bm25_v1")
args = parser.parse_args()
base = args.output_dir / "holdout_predictions"
load = lambda suffix: json.loads(base.with_suffix(suffix).read_text(encoding="utf-8"))
metrics, score, rows = load(".metrics.json"), load(".score.json"), load(".diagnostics.json")
config = json.loads((args.output_dir / "frozen_configuration.json").read_text(encoding="utf-8"))
if len(rows) != 53 or metrics["questions"] != 53:
    raise ValueError("Expected the complete fixed 53-question holdout")
classes = Counter()
for row in rows:
    if row["value_correct"]:
        category = "correct_value_and_citations" if row["ref_f1"] == 1 else "correct_value_citation_gap"
    elif row["gold_unanswerable"]:
        category = "answered_unanswerable_question"
    elif row["predicted_value"] == "is_blank":
        category = "model_abstained_on_answerable" if row["decision"] == "model_abstained" else "validator_rejected_answerable"
    elif row["retrieved_gold_ref_fraction"] == 0:
        category = "wrong_value_gold_document_absent_from_context"
    else:
        category = "wrong_value_gold_document_present_in_context"
    row["error_category"] = category
    classes[category] += 1
correct = sum(row["value_correct"] for row in rows)
na = [row for row in rows if row["gold_unanswerable"]]
refused_na = sum(row["predicted_value"] == "is_blank" for row in na)
answered = [row for row in rows if row["predicted_value"] != "is_blank"]
answerable = [row for row in rows if not row["gold_unanswerable"]]
context_recall = sum(row["retrieved_gold_ref_fraction"] for row in answerable) / len(answerable)
summary = {"error_categories": dict(classes), "correct_values": correct, "questions": len(rows),
           "gold_unanswerable": len(na), "correctly_refused_unanswerable": refused_na,
           "answered_questions": len(answered),
           "generator_context_mean_gold_document_recall": context_recall,
           "generator_context_fully_covered_questions": sum(row["retrieved_gold_ref_fraction"] == 1 for row in answerable),
           "value_accuracy_among_answered": sum(row["value_correct"] for row in answered) / len(answered) if answered else None,
           "per_question": rows}
(args.output_dir / "error_analysis.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
inference = config["inference"]
official = score["official_breakdown"]
lines = ["# End-to-end BM25 + local LLM baseline — 2026-10-14", "",
         "This is the first complete held-out answer evaluation. Predictions were generated by the frozen pipeline and scored with the unmodified supplied `Score.py`. No test questions or leaderboard feedback were used.", "",
         "## Measured results", "", "| Metric | Result |", "| --- | ---: |",
         f"| Official WattBot Score | {score['official_score']:.6f} |",
         f"| Correct answer values | {correct}/{len(rows)} ({100*correct/len(rows):.2f}%) |",
         f"| Mean citation F1 from official scorer | {official['ref_f1']:.6f} |",
         f"| Abstentions across all questions | {metrics['abstentions']}/{len(rows)} |",
         f"| Correct refusals on gold-unanswerable questions | {refused_na}/{len(na)} |",
         f"| Mean gold-document recall inside the generator's top-8-chunk context | {context_recall:.6f} |",
         f"| Mean / median / p95 question latency, seconds | {metrics['mean_seconds']:.2f} / {metrics['median_seconds']:.2f} / {metrics['p95_seconds']:.2f} |",
         f"| Sum of per-question time, seconds | {metrics['total_seconds']:.2f} |",
         f"| Full invocation wall time, seconds | {metrics['wall_seconds_this_invocation']:.2f} |",
         f"| External paid API cost, USD | {metrics['external_api_cost_usd']} |", "",
         "Latency includes retrieval, local generation and evidence validation; model loading on the first question is included if needed. Model residency and GPU scheduling affect these one-run timings. Electricity, hardware depreciation and download bandwidth costs were not measured.", "",
         "Context recall is computed on the 51 answerable questions from the exact chunks supplied to the generator. It differs from the earlier distinct-document Recall@5 experiment: multiple of the eight chunks may come from the same document.", "",
         "## Frozen setup and separation", "",
         f"- Model: `{inference['model']}`, MXFP4; digest `{inference['model_digest']}`.",
         f"- Ollama native chat; context {inference['context_length']} tokens; maximum generated tokens {inference['max_tokens']}; thinking `{inference['thinking']}`; temperature 0; seed 42.",
         "- Hardware: local NVIDIA RTX 5070 Ti, 16 GB VRAM. No model training or external inference provider.",
         f"- BM25 over all 122 PDFs / 6,540 text chunks; generator receives the top {inference['top_k']} chunks, plus the question and benchmark-provided answer unit. Training answers are not indexed or sent to the generator.",
         "- 192 development questions are separate from the deterministic 53-question holdout. A small 11-question development set covered evidence types and three unanswerable examples.",
         "- Initial development debugging exposed the Ollama default 4,096-token window: responses could terminate before producing answer JSON. That partial run remains in `outputs/development_v1` and is not reported as a benchmark. Native Ollama requests with an explicit 8,192-token context were validated on development_v2 before freezing this holdout run.",
         "- Model digest, inference parameters, data hashes and core source hashes were frozen in `configs/bm25_local_v1.json` before held-out generation. No prompt or retrieval parameter was tuned against this run's held-out answers.", "",
         "## Automatic error groups", "", "| Group | Questions |", "| --- | ---: |"]
lines.extend(f"| {key} | {value} |" for key, value in sorted(classes.items()))
lines += ["", "These groups describe observable pipeline behavior. A gold document in the context does not establish that the required passage, table cell or figure is present. Assigning a more specific cause such as arithmetic error requires reading the actual trace.", "",
          "A validator rejection also does not establish that the model's proposed value was correct. For example, q011's raw response proposed the wrong model while simultaneously returning a blank value. Relaxing quotation checks alone would not resolve all rejected examples.", "",
          "## Answer-value errors by evidence type", "", "| Type | Wrong / total |", "| --- | ---: |"]
for label, bucket in official["per_type"].items():
    lines.append(f"| {label} | {bucket['wrong']} / {bucket['n']} |")
lines += ["", "Evidence-type flags overlap. The shipped scorer's per-type `score` calculation uses legacy weights different from its headline score; the table above therefore reports its value-error counts only. The headline WattBot Score is used unchanged.", "",
          "## Representative measured cases", ""]
seen = set()
for row in rows:
    category = row["error_category"]
    if row["value_correct"] or category in seen:
        continue
    seen.add(category)
    question = row["question"].replace("\n", " ")
    lines += [f"### {row['id']} — {category}", "", question, "",
              f"- Expected value: `{row['gold_value']}`; prediction: `{row['predicted_value']}`.",
              f"- Gold sources: `{row['gold_ref_ids']}`; cited sources: `{row['predicted_ref_ids']}`.",
              f"- Decision: `{row['decision']}`; per-row official score: {row['official_row_score']:.6f}.", ""]
    if len(seen) >= 5:
        break
lines += ["## Evidence checks and limits", "",
          "Accepted citations must refer to a retrieved document, and each quoted span must occur in a retrieved passage. Whitespace-only differences can be restored to the actual source substring; arbitrary text or punctuation substitutions are not accepted. Refusals blank all required evidence fields. These checks verify quotation provenance, not the semantic correctness of the generated claim or calculation.", "",
          "The holdout is small, with only two gold-unanswerable questions. Refusal performance on that tiny subset cannot establish reliability in general. PDF text extraction can omit table structure and figure contents. Eleven metadata source URLs have no pinned version; recorded mirror selections do not prove the authors' historical versions. See `corpus_acquisition.md`.", "",
          "## Artifacts and reproduction", "",
          "The local output directory contains prediction/solution CSVs, raw per-question traces, run settings, token usage, latency, official score output, per-question diagnostics and error analysis. These data artifacts remain Git-ignored.", "",
          "```powershell", "uv venv .venv-baseline --python 3.12",
          "uv pip install --python .venv-baseline/Scripts/python.exe -r requirements-baseline.txt",
          "uv pip install --python .venv-baseline/Scripts/python.exe --no-deps -e .",
          ".venv-baseline/Scripts/python.exe scripts/run_local_baseline.py --output-dir outputs/reproduced_bm25_v1",
          "# Continue an interrupted run with the same data, prompt and model:",
          ".venv-baseline/Scripts/python.exe scripts/run_local_baseline.py --output-dir outputs/reproduced_bm25_v1 --resume", "```", "",
          "The pinned Python dependencies were installed successfully in a separate local environment. `reports/runtime_snapshot.json` records the measured runtime. See `error_review_v1.md` for a manual review of selected measured failures.", "",
          "The frozen file and model hashes must match. Seed and temperature control sampling settings; backend, hardware or runtime changes may still change predictions or timing. Compare future retrieval variants under the same split and report this baseline alongside them."]
report = root / "reports/answer_baseline.md"
report.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(json.dumps({key: value for key, value in summary.items() if key != "per_question"}, indent=2))
print(report)
